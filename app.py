"""
app.py  --  the screen. Run with:  streamlit run app.py

Pipeline:  screenshots -> numbers (Claude vision) -> checks (plain Python) -> explanation
"""
import os
import tempfile

import pandas as pd
import streamlit as st

from checks import load_trips, run_all_checks
from explain import explain

st.set_page_config(page_title="Trip Payout Checker", page_icon="🧾", layout="wide")

st.title("🧾 Trip Payout Checker")
st.caption(
    "Upload a week of delivery trip-earnings screens. The tool reads them, checks that the "
    "numbers are consistent, and drafts a message you can send to support. "
    "It flags things worth asking about. It never says anyone cheated."
)

# ---------------- sidebar ----------------
with st.sidebar:
    st.header("Settings")
    source = st.radio(
        "Data",
        ["Sample week (30 synthetic trips)", "Upload my screenshots"],
    )
    engine_label = st.radio("Reading method (for uploads)",
                            ["Free OCR (offline)", "Claude vision (needs credit)"])
    engine = "ocr" if engine_label.startswith("Free") else "claude"
    use_claude = st.checkbox("Use Claude to write the explanation", value=False,
                             help="Needs API credit. If it fails, a built-in template is used.")
    language = st.selectbox("Language", ["English", "Tamil"], disabled=not use_claude)
    st.divider()
    st.caption("Sample data is synthetic and was generated by code. Not real people's pay.")


# ---------------- get the trips table ----------------
@st.cache_data(show_spinner=False)
def cached_extract(file_name, file_bytes, engine):
    """Read one uploaded screenshot (cached so we never read or pay twice)."""
    from extract import extract_one       # imported here: needs the API key only when used

    suffix = os.path.splitext(file_name)[1] or ".png"
    with tempfile.NamedTemporaryFile(delete=False, suffix=suffix) as tmp:
        tmp.write(file_bytes)
        path = tmp.name
    try:
        return extract_one(path, engine)
    finally:
        os.remove(path)


df = None
if source.startswith("Sample"):
    try:
        df = load_trips("answers")
        st.info("Showing the synthetic sample week. Switch to 'Upload my screenshots' in the "
                "sidebar to try your own.")
    except FileNotFoundError:
        st.error("Sample data not found. Run `python generate_data.py` first.")
else:
    files = st.file_uploader("Upload trip screenshots (PNG/JPG)",
                             type=["png", "jpg", "jpeg"], accept_multiple_files=True)
    if files and st.button("Check my week", type="primary"):
        rows, failed = [], []
        bar = st.progress(0.0, text="Reading screenshots...")
        for i, f in enumerate(files):
            try:
                r = cached_extract(f.name, f.getvalue(), engine)
                rows.append({
                    "file": f.name, "km": r.get("distance_km"), "mins": r.get("trip_time_mins"),
                    "trip_pay": r.get("trip_pay"),
                    "return_pay": r.get("long_distance_return_pay") or 0.0,
                    "total": r.get("total_earnings"),
                })
            except Exception as e:
                failed.append(f"{f.name}: {str(e)[:150]}")
            bar.progress((i + 1) / len(files), text=f"Read {i + 1} of {len(files)}")
        bar.empty()
        for msg in failed:
            st.error(f"Could not read {msg}")
        if rows:
            df = pd.DataFrame(rows).dropna(subset=["km", "trip_pay", "total"])
            if len(df) < 8:
                st.warning("Fewer than ~8 readable trips: the rate comparison is weak with so "
                           "few trips. Sum and return-pay checks still work.")

# ---------------- run checks + show results ----------------
if df is not None and not df.empty:
    flags = run_all_checks(df)
    flagged_files = {}
    for f in flags:
        flagged_files.setdefault(f["file"], []).append(f["check"])

    out = df.copy()
    out["status"] = out["file"].map(
        lambda n: "⚠ " + ", ".join(flagged_files[n]) if n in flagged_files else "OK")
    out = out.rename(columns={"km": "distance (km)", "mins": "time (min)",
                              "trip_pay": "trip pay", "return_pay": "return pay"})

    c1, c2, c3 = st.columns(3)
    c1.metric("Trips checked", len(df))
    c2.metric("Trips flagged", len(flagged_files))
    c3.metric("Rupees worth asking about", f"₹{sum(f['rupees'] for f in flags):,.0f}")

    st.subheader("Trips")
    st.dataframe(out, hide_index=True)

    st.subheader("What looks inconsistent")
    if not flags:
        st.success("Nothing looks inconsistent in these trips.")
    for f in flags:
        st.warning(f"**{f['file']}** ({f['check']} check): {f['detail']}")

    if flags:
        with st.spinner("Writing explanation..."):
            explanation, message, src = explain(flags, language, use_claude)
        if use_claude and src == "template":
            st.caption("Claude was unavailable (check API credit), so the built-in template was used.")
        st.subheader("Explanation")
        st.write(explanation)
        st.subheader("Draft message to support")
        st.text_area("Copy and edit before sending", message, height=260)

    with st.expander("How this works"):
        st.markdown(
            "1. **Read**: Claude vision (or a free offline OCR reader) turns each screenshot into numbers.\n"
            "2. **Check**: plain Python does the arithmetic and comparisons (no AI, so no maths "
            "mistakes).\n"
            "3. **Explain**: Claude (or a template) turns flags into simple words.\n\n"
            "**Limits:** pay can vary for legitimate reasons. A flag is a question to ask, not "
            "proof of an error. Checked on synthetic data only so far."
        )
