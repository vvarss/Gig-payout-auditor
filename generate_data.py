"""
generate_data.py
Creates fake delivery "trip earnings" screenshots + a separate answer key.

Run:  python generate_data.py
Output: data/synthetic/trip_01.png ... and data/synthetic/answers.json

The app name is made up ("QuickDrop"). Layout is only *inspired* by real apps.
All numbers are generated by a formula we control, so we always know the truth.
"""
import json
import os
import random

from PIL import Image, ImageDraw, ImageFilter, ImageFont

# ---------- settings you can change ----------
NUM_TRIPS = 30
SEED = 42                      # same seed = same data every run
OUT_DIR = os.path.join("data", "synthetic")
W, H = 720, 1560               # phone-like size

# Our made-up pay rules (the "truth" the checker must discover)
BASE = 20.0                    # rupees
PER_KM = 7.5
PER_MIN = 0.4
RETURN_RATE = 1.80             # rupees per km, only on long trips
RETURN_MIN_KM = 15.0
NOISE = 0.08                   # +-3% natural variation
# ---------------------------------------------

random.seed(SEED)


def find_font(size, bold=False):
    """Try common fonts on Windows / Mac / Linux, fall back to default."""
    names = (
        ["segoeuib.ttf", "arialbd.ttf", "DejaVuSans-Bold.ttf"]
        if bold
        else ["segoeui.ttf", "arial.ttf", "DejaVuSans.ttf"]
    )
    for n in names:
        try:
            return ImageFont.truetype(n, size)
        except OSError:
            continue
    return ImageFont.load_default()


def inr(x):
    return f"\u20b9{x:,.2f}"


def draw_screen(path, trip, shown_total, look):
    """Draw one screen. `trip` has trip_pay, return_pay (or None), km, mins."""
    bg = (0, 0, 0)
    img = Image.new("RGB", (W, H), bg)
    d = ImageDraw.Draw(img)

    # green header with curved bottom
    green = look["green"]
    d.rectangle([0, 0, W, 470], fill=green)
    d.ellipse([-220, 400, W + 220, 760], fill=bg)   # black bowl carves the curve

    # fake status bar
    d.text((30, 28), look["clock"], font=find_font(30, True), fill="white")
    d.text((W - 140, 28), "5G  77%", font=find_font(26), fill="white")

    # tick circle
    cx, cy, r = W // 2, 330, 85
    d.ellipse([cx - r - 14, cy - r - 14, cx + r + 14, cy + r + 14], fill=bg)
    d.ellipse([cx - r, cy - r, cx + r, cy + r], fill=(0, 150, 80))
    d.line([(cx - 40, cy + 5), (cx - 10, cy + 38), (cx + 42, cy - 30)],
           fill="white", width=16, joint="curve")

    # titles + big total
    d.text((W // 2, 520), "Great job! Delivery complete",
           font=find_font(36, True), fill="white", anchor="mm")
    d.text((W // 2, 575), "Trip earnings",
           font=find_font(36, True), fill="white", anchor="mm")
    d.text((W // 2, 660), inr(shown_total),
           font=find_font(78, True), fill="white", anchor="mm")

    # card
    card = (22, 740, W - 22, 1090)
    d.rounded_rectangle(card, radius=22, fill=(48, 48, 48), outline=(90, 90, 90), width=2)

    f = find_font(32)
    y = 790
    rows = [("Trip pay", inr(trip["trip_pay"]))]
    if trip["return_pay"] is not None:
        rows.append(("Long distance return pay", inr(trip["return_pay"])))
    for label, val in rows:
        d.text((70, y), label, font=f, fill="white")
        d.text((W - 50, y), val, font=f, fill="white", anchor="ra")
        y += 70
    # divider
    y += 5
    d.line([(22, y), (W - 22, y)], fill=(90, 90, 90), width=2)
    y += 40
    d.text((70, y), "Trip distance", font=f, fill="white")
    d.text((W - 50, y), f"{trip['km']} kms", font=f, fill="white", anchor="ra")
    y += 70
    d.text((70, y), "Trip time", font=f, fill="white")
    d.text((W - 50, y), f"{trip['mins']} mins", font=f, fill="white", anchor="ra")

    # bottom button
    d.rounded_rectangle((22, 1400, W - 22, 1490), radius=22, fill="white")
    d.text((W // 2, 1445), "Get next order", font=find_font(36), fill="black", anchor="mm")

    # "photo of a phone" variation: slight blur + rotation
    if look["blur"]:
        img = img.filter(ImageFilter.GaussianBlur(look["blur"]))
    if look["rotate"]:
        img = img.rotate(look["rotate"], expand=False, fillcolor=(20, 20, 20))
    img.save(path)


def make_trip():
    km = round(random.uniform(2.5, 25.0), 1)
    mins = int(km * random.uniform(2.0, 3.0) + random.randint(5, 15))
    expected = BASE + PER_KM * km + PER_MIN * mins
    trip_pay = round(expected * (1 + random.uniform(-NOISE, NOISE)), 2)
    return_pay = round(RETURN_RATE * km, 2) if km >= RETURN_MIN_KM else None
    return {"km": km, "mins": mins, "trip_pay": trip_pay, "return_pay": return_pay}


def main():
    os.makedirs(OUT_DIR, exist_ok=True)
    trips = [make_trip() for _ in range(NUM_TRIPS)]

    # --- plant errors: pick specific trips and break them ---
    long_trips = [i for i, t in enumerate(trips) if t["return_pay"] is not None]
    other = [i for i in range(NUM_TRIPS) if i not in long_trips]
    random.shuffle(long_trips)
    random.shuffle(other)

    planted = {}  # index -> error type
    if len(long_trips) >= 2:
        planted[long_trips[0]] = "missing_return_pay"
        planted[long_trips[1]] = "missing_return_pay"
    # total shown does not match the parts
    planted[other[0]] = "total_mismatch_plus"
    planted[other[1]] = "total_mismatch_minus"
    # pay far below normal for that distance
    planted[other[2]] = "low_rate"

    answers = []
    for i, t in enumerate(trips):
        kind = planted.get(i, "none")
        true_trip = dict(t)
        shown = dict(t)

        if kind == "missing_return_pay":
            shown["return_pay"] = None          # line vanishes from the screen
        if kind == "low_rate":
            shown["trip_pay"] = round(t["trip_pay"] * 0.55, 2)

        parts = shown["trip_pay"] + (shown["return_pay"] or 0)
        shown_total = round(parts, 2)
        if kind == "total_mismatch_plus":
            shown_total = round(parts + 10, 2)
        elif kind == "total_mismatch_minus":
            shown_total = round(parts - 15, 2)

        # visual variety: some clean, some blurry/tilted, different clock/green
        r = random.random()
        look = {
            "green": random.choice([(16, 185, 105), (14, 170, 95), (20, 190, 110)]),
            "clock": f"{random.randint(9, 22)}:{random.randint(10, 59)}",
            "blur": 0.0 if r < 0.6 else random.choice([0.8, 1.2]),
            "rotate": 0 if r < 0.75 else random.choice([-1.5, 1.5]),
        }

        fname = f"trip_{i + 1:02d}.png"
        draw_screen(os.path.join(OUT_DIR, fname), shown, shown_total, look)

        answers.append({
            "file": fname,
            "error": kind,                       # "none" = normal trip
            "shown_total": shown_total,
            "shown_trip_pay": shown["trip_pay"],
            "shown_return_pay": shown["return_pay"],
            "km": t["km"],
            "mins": t["mins"],
            "should_have_return_pay": t["return_pay"] is not None,
        })

    with open(os.path.join(OUT_DIR, "answers.json"), "w", encoding="utf-8") as f:
        json.dump(answers, f, indent=2, ensure_ascii=False)

    n_err = sum(1 for a in answers if a["error"] != "none")
    print(f"Made {NUM_TRIPS} screenshots in {OUT_DIR} ({n_err} with planted errors).")
    print("Answer key: answers.json  (do NOT upload this to the app).")


if __name__ == "__main__":
    main()
